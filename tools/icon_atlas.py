#!/usr/bin/env python3
"""Build legacy DDS portrait atlases and SQL from the reviewed PNG catalog.

Requires Pillow >= 11.3 only when regenerating artwork; ordinary mod builds
package the committed DDS files without an imaging dependency.
"""
import json
import math
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZES = (256, 128, 80, 64, 45, 32)
GROUP_SIZES = {'BUILDINGS': SIZES, 'PROGRAMS': SIZES,
               'TECHNOLOGIES': (256, 214, 128, 80, 64, 45)}
GRID = 4
GEOMETRY = json.loads((ROOT / 'assets/icons/geometry.json').read_text())


@lru_cache(maxsize=None)
def portrait_frame(group, size):
    """Geometry is part of the texture; transparent padding is not UI spacing."""
    from PIL import Image, ImageDraw

    scale = GEOMETRY['supersampling']
    rim_pixels = GEOMETRY['profiles'][group].get('rim_widths', {}).get(str(size), 0)
    diameter = GEOMETRY['diameters'][str(size)] + 2 * rim_pixels
    width = round(diameter * scale)
    mask = Image.new('L', (width, width))
    ImageDraw.Draw(mask).ellipse((0, 0, width - 1, width - 1), fill=255)
    frame = Image.new('RGBA', (width, width))
    if rim_pixels:
        # Technologies alone receive the explicit baked rim requested by the
        # user. Buildings/programs are rendered without their painted borders.
        radius = width / 2
        rim = rim_pixels * scale
        stops = ((0, (69, 53, 29)), (.12, (164, 132, 72)),
                 (.32, (246, 234, 191)), (.58, (199, 168, 103)),
                 (.86, (121, 94, 51)), (1, (53, 48, 36)))
        pixels = []
        for y in range(width):
            for x in range(width):
                dx, dy = x + .5 - radius, y + .5 - radius
                distance = math.hypot(dx, dy)
                t = (radius - distance) / rim
                if not 0 <= t <= 1:
                    pixels.append((0, 0, 0, 0))
                    continue
                for (lo, a), (hi, b) in zip(stops, stops[1:]):
                    if lo <= t <= hi:
                        mix = (t - lo) / (hi - lo)
                        light = 1 + .13 * (-dx - dy) / (radius * math.sqrt(2))
                        pixels.append(tuple(min(255, round((v + (w-v) * mix) * light))
                                            for v, w in zip(a, b)) + (255,))
                        break
        frame.putdata(pixels)
    return diameter, mask, frame


def render_portrait(master, group, size):
    from PIL import Image

    scale = GEOMETRY['supersampling']
    profile = GEOMETRY['profiles'][group]
    diameter, mask, frame = portrait_frame(group, size)
    width = diameter * scale
    inset = profile.get('rim_widths', {}).get(str(size), 0) * scale
    art = master.crop(profile['source_crop']).resize(
        (width - 2 * inset, width - 2 * inset), Image.Resampling.LANCZOS)
    disk = Image.new('RGBA', (width, width), '#101a24')
    disk.alpha_composite(art, (inset, inset))
    disk.alpha_composite(frame)
    disk.putalpha(mask)
    cell = Image.new('RGBA', (size * scale, size * scale))
    offset = (size * scale - width) // 2
    cell.paste(disk, (offset, offset))
    return cell.resize((size, size), Image.Resampling.LANCZOS)


def generate():
    from PIL import Image, ImageDraw, ImageFont

    source = ROOT / 'assets/icons'
    icons = json.loads((source / 'catalog.json').read_text())['icons']
    output = ROOT / 'mod/Art/Icons'
    output.mkdir(parents=True, exist_ok=True)
    sql = ['-- Generated by tools/icon_atlas.py; artwork selections: assets/icons/catalog.json.',
           '-- Portraits only: no gameplay parameters or world models are changed.',
           'INSERT INTO IconTextureAtlases (Atlas, IconSize, Filename, IconsPerRow, IconsPerColumn) VALUES']
    rows = []
    for group, sizes in GROUP_SIZES.items():
        selected = [icon for icon in icons if icon['atlas'] == group]
        assert [icon['index'] for icon in selected] == list(range(len(selected)))
        assert len(selected) <= GRID * GRID
        for size in sizes:
            atlas = Image.new('RGBA', (size * GRID, size * GRID))
            for icon in selected:
                with Image.open(source / icon['file']) as master:
                    assert master.mode == 'RGBA' and master.size == (512, 512)
                    portrait = render_portrait(master, group, size)
                index = icon['index']
                atlas.paste(portrait, ((index % GRID) * size, (index // GRID) * size))
            filename = f'Refined_{group.title()}_{size}.dds'
            # Uncompressed legacy A8R8G8B8: exact alpha, no DX10 header or mipmaps.
            # 45px cells do not align to DXT blocks, so use the same lossless
            # format at every size to avoid bleeding across neighboring portraits.
            atlas.save(output / filename)
            rows.append(f" ('REFINED_{group}_ATLAS', {size}, '{filename}', {GRID}, {GRID})")
    sql.append(',\n'.join(rows) + ';')
    for icon in icons:
        table = ('Buildings' if icon['type'].startswith('BUILDING_') else
                 'Projects' if icon['type'].startswith('PROJECT_') else
                 'Technologies' if icon['type'].startswith('TECH_') else 'Processes')
        sql.append(f"UPDATE {table} SET IconAtlas = 'REFINED_{icon['atlas']}_ATLAS', "
                   f"PortraitIndex = {icon['index']} WHERE Type = '{icon['type']}';")
    (ROOT / 'mod/SQL/Icons.sql').write_text('\n'.join(sql) + '\n')

    # Separate sheets preserve the user's building/program review numbering.
    font = None
    for candidate in ('/System/Library/Fonts/Supplemental/Arial.ttf',
                      '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'):
        if Path(candidate).exists():
            font = ImageFont.truetype(candidate, 15)
            break
    for technology_sheet in (False, True):
        selected = [icon for icon in icons if (icon['atlas'] == 'TECHNOLOGIES') == technology_sheet]
        render_preview(selected, output, source, font, technology_sheet)
    render_fit_comparison(icons, output, source, font)
    print(f'Generated {len(icons)} portraits, {sum(map(len, GROUP_SIZES.values()))} DDS atlases and SQL/Icons.sql')


def render_preview(icons, output, source, font, technology_sheet):
    from PIL import Image, ImageDraw

    columns, cell_width = (2, 550) if technology_sheet else (3, 366)
    sheet = Image.new('RGB', (1100, ((len(icons) + columns - 1) // columns) * 235), '#23313c')
    draw = ImageDraw.Draw(sheet)
    for i, icon in enumerate(icons):
        x, y = (i % columns) * cell_width, (i // columns) * 235
        portraits = []
        for size in (256, 45):
            with Image.open(output / f"Refined_{icon['atlas'].title()}_{size}.dds") as atlas:
                left, top = icon['index'] % GRID * size, icon['index'] // GRID * size
                portraits.append(atlas.crop((left, top, left + size, top + size)).convert('RGBA'))
        large = portraits[0].resize((180, 180), Image.Resampling.LANCZOS)
        small = portraits[1]
        sheet.paste(large, (x + 24, y + 5), large)
        sheet.paste(small, (x + 230, y + 70), small)
        draw.text((x + 12, y + 187), f"{i + 1:02}. {icon['label']}", font=font, fill='white')
        draw.text((x + 12, y + 209), icon['era'], font=font, fill='#a7c2d6')
    sheet.save(source / ('technology-preview.jpg' if technology_sheet else 'preview.jpg'), quality=93)


def render_fit_comparison(icons, output, source, font):
    """Texture comparison, explicitly not an in-game rendering claim."""
    from PIL import Image, ImageDraw

    sheet = Image.new('RGB', (1080, 1000), '#23313c')
    draw = ImageDraw.Draw(sheet)
    draw.text((20, 12), 'Штатная карточка BNW — присланный игровой скриншот', font=font, fill='white')
    with Image.open(source / 'references/bnw-technology-card.png') as reference:
        sheet.paste(reference.resize((590, 168)), (20, 40))
    draw.text((650, 60), 'Эталон: поле 64×64, рисунок 44 px', font=font, fill='white')
    draw.text((650, 88), 'Открытия: поле 45×45, круг 31 px', font=font, fill='white')
    draw.text((20, 220), 'Ниже — реальные текстуры до/после, увеличение ×3', font=font, fill='white')
    draw.text((270, 250), 'Было', font=font, fill='white')
    draw.text((640, 250), 'Стало', font=font, fill='white')
    examples = [('Прикладной ИИ', 64, ['TECH_REFINED_AI']),
                ('Здания: дата-центр', 45, ['BUILDING_REFINED_DATA_CENTER']),
                ('Проекты из примера', 45, ['PROJECT_REFINED_MARS_COLONY',
                                         'PROJECT_REFINED_CULTURAL_EXPANSION'])]
    for row, (label, size, types) in enumerate(examples):
        y = 286 + row * 210
        draw.text((20, y + 35), label, font=font, fill='white')
        for col, old in enumerate((True, False)):
            strip = Image.new('RGBA', (size + (len(types) - 1) * 38, size), '#101b20')
            for k, type_ in enumerate(types):
                icon = next(icon for icon in icons if icon['type'] == type_)
                if old:
                    with Image.open(source / icon['file']) as master:
                        cell = master.resize((size, size), Image.Resampling.LANCZOS)
                else:
                    with Image.open(output / f"Refined_{icon['atlas'].title()}_{size}.dds") as atlas:
                        x, top = icon['index'] % GRID * size, icon['index'] // GRID * size
                        cell = atlas.crop((x, top, x + size, top + size)).convert('RGBA')
                strip.alpha_composite(cell, (k * 38, 0))
            enlarged = strip.resize((strip.width * 3, strip.height * 3), Image.Resampling.NEAREST)
            sheet.paste(enlarged, (270 + col * 370, y), enlarged)
            draw.text((270 + col * 370, y + size * 3 + 3),
                      f'{size}×{size} px' + (' на ячейку' if len(types) > 1 else ''),
                      font=font, fill='#aac4d7')
    draw.text((20, 950), 'Технологии — с золотой рамкой; здания, проекты и процесс — без ободка.',
              font=font, fill='white')
    draw.text((20, 975), 'Это сравнение текстур, а не новый запуск BNW. Назначения всех изображений сохранены.',
              font=font, fill='#aac4d7')
    sheet.save(source / 'fit-comparison.jpg', quality=95)


if __name__ == '__main__':
    generate()
